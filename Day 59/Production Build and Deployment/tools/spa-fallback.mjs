/* Day 59 - the two files a static host needs that `ng build` does not write,
 * and one check on the file it does.
 *
 * Run after a build, with the output directory and, optionally, the base href
 * the build was supposed to produce:
 *
 *     node tools/spa-fallback.mjs dist/contacts/browser /Frontend-Training/
 *
 * 404.html
 *   A single-page app owns its URLs, and a static host does not know that.
 *   `/contacts/c1` is a route, not a file, so a GET for it finds nothing and
 *   the host answers 404 with its own page. The app never loads, so its router
 *   never gets the chance to recognise the URL - which is why "it works until
 *   you refresh" is the single most common way a correct SPA looks broken in
 *   production.
 *
 *   GitHub Pages serves `404.html` for anything it cannot find, so a COPY of
 *   index.html under that name is the whole fix: the host answers the deep link
 *   with the app, the app boots, the router reads `location.pathname` and
 *   renders the right page. The response status really is 404, which search
 *   engines are right to dislike and a human cannot tell; a host with a proper
 *   rewrite rule (nginx `try_files`, Netlify `_redirects`, Cloudflare Pages,
 *   S3+CloudFront custom error responses) answers 200 instead. Those are in
 *   DEPLOYING.md. This file is the version that needs no host configuration at
 *   all, which is why it is the one in the build script.
 *
 * .nojekyll
 *   GitHub Pages runs everything through Jekyll unless this file is present,
 *   and Jekyll silently skips files and directories whose names start with an
 *   underscore. Angular's output does not use leading underscores today, so
 *   this is insurance rather than a fix - and it is one empty file against a
 *   failure mode that presents as "one chunk 404s in production and nowhere
 *   else".
 */
import { copyFileSync, existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = process.argv[2];
const expected = process.argv[3];

if (out === undefined) {
    console.error('usage: node tools/spa-fallback.mjs <output directory> [expected base href]');
    process.exit(2);
}

const index = join(out, 'index.html');

/* Fail loudly rather than writing a 404.html nobody asked for. A silent
   success here would mean a deploy script that "worked" against an empty
   directory - which is how an entire site goes missing with a green build. */
if (!existsSync(index)) {
    console.error(`spa-fallback: no index.html in ${out} - did the build run?`);
    process.exit(1);
}

const html = readFileSync(index, 'utf8');

/* The base href, read the way a browser reads it: comments first.

   This started as `grep -q '<base href="/Frontend-Training/">' index.html` in
   the CI workflow, and that check was worthless. `src/index.html` has a
   comment ABOUT the base href which contains the string `<base href="/">`,
   and once I wrote today's explanation into it, the string
   `<base href="/Frontend-Training/">` as well - so the grep passed on text
   that no browser will ever act on. A build with the flag missing would have
   gone green.

   Stripping comments is the whole fix, and it is the reason this check lives
   in a script instead of a workflow line: a regex over HTML is wrong often
   enough that it should be somewhere it can be read and corrected, not
   wedged into YAML. It is still a regex over HTML. What makes it acceptable
   is that the input is one file, generated by a tool, whose `<base>` element
   this script only ever has to find - not parse arbitrary markup. */
const baseHref = /<base\s[^>]*href="([^"]*)"/i.exec(html.replace(/<!--[\s\S]*?-->/g, ''))?.[1];

if (baseHref === undefined) {
    console.error('spa-fallback: no <base href> in the built index.html');
    console.error('  Without one the router and API_BASE have nothing to resolve against.');
    process.exit(1);
}

/* The expected value is passed in rather than inferred, which means the base
   href appears twice in `package.json` - once as `--base-href` and once here.
   That is the point: the failure this catches is the flag not arriving, and a
   check derived from the flag could not catch it. Two copies that have to
   agree is a cheap price for a build that cannot lie about where it is going
   to be served from. */
if (expected !== undefined && baseHref !== expected) {
    console.error(`spa-fallback: base href is "${baseHref}", expected "${expected}"`);
    console.error('  The --base-href flag did not reach the build, or the two disagree.');
    process.exit(1);
}

const fallback = join(out, '404.html');
copyFileSync(index, fallback);

const nojekyll = join(out, '.nojekyll');
writeFileSync(nojekyll, '');

console.log(
    `spa-fallback: base href "${baseHref}", ` +
    `404.html written (${statSync(fallback).size} bytes) and .nojekyll created`
);
